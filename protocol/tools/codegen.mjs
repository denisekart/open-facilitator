// Plan 01 Step 6: regenerate committed C#/TS DTOs from the frozen JSON Schemas.
// One render pass per language over the sorted schema set so shared `$defs`
// types (ArtifactRef, Deliverable, ...) are emitted exactly once. Type names
// come from each schema's `title` (filename-derived), e.g.
// command.work.assign.v1.json -> WorkAssignCommandV1Data.
//
// Run: pnpm protocol:codegen   (drift gate: git diff --exit-code on outputs)
import { readdirSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("../..", import.meta.url));
const schemaDirs = [join(repo, "protocol/json-schema"), join(repo, "protocol/cloudevents-schemas")];
// Documented skip list: schemas that SHIP (mirrored to the package, validated
// by both fixture harnesses) but are excluded from the quicktype DTO pass.
// adapter.v1.json is a oneOf frame union: flattened, quicktype merges the
// variants into one interface whose `reason` union cannot carry a free-form
// stop/reject reason, and its $ref into capability-manifest.v1.json renames
// the published CapabilityDescriptor types. Contract consumers (fixture
// harnesses, docs) validate against the schema, not the DTOs, so no generated
// name is worth that churn.
const CODEGEN_SKIP = new Set(["adapter.v1.json"]);
const schemas = schemaDirs
  .flatMap((d) => readdirSync(d).filter((f) => f.endsWith(".json")).map((f) => join(d, f)))
  .sort();
const dtoSchemas = schemas.filter((s) => !CODEGEN_SKIP.has(basename(s)));

const TS_OUT = join(repo, "src/protocol/src/generated");
const CS_OUT = join(repo, "protocol/dotnet/Ofac.Protocol/Generated");
// The published @ofac/protocol package ships the schemas as plain JSON files
// (loaded via import attributes); codegen mirrors them into the package tree.
const SCHEMA_OUT = join(repo, "src/protocol/schemas");

function quicktype(args) {
  const r = spawnSync("npx", ["--no-install", "quicktype", ...args], {
    cwd: repo,
    encoding: "utf8",
    stdio: ["ignore", "inherit", "inherit"],
  });
  if (r.status !== 0) {
    console.error(`quicktype failed (${r.status}): ${args.join(" ")}`);
    process.exit(r.status ?? 1);
  }
}

for (const dir of [TS_OUT, CS_OUT]) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}

// TypeScript: interfaces only — runtime validation is ajv's job.
quicktype([
  "-s", "schema", ...dtoSchemas,
  "--lang", "ts", "--just-types", "--no-date-times", "--alphabetize-properties", "--quiet",
  "-o", join(TS_OUT, "types.ts"),
]);
// quicktype emits a vestigial unexported `SharedDefinitions` alias that trips
// noUnusedLocals in consumers' typecheck; drop it so the drift gate stays clean.
{
  const p = join(TS_OUT, "types.ts");
  writeFileSync(p, readFileSync(p, "utf8").replace(/^type SharedDefinitions = unknown;\n+/m, ""));
}
writeFileSync(
  join(TS_OUT, "index.ts"),
  `// Generated by protocol/tools/codegen.mjs — do not edit.\nexport * from "./types.js";\n`,
);

// C#: System.Text.Json attributes, property names verbatim (wire is lowercase/camel as-is).
quicktype([
  "-s", "schema", ...dtoSchemas,
  "--lang", "cs", "--framework", "SystemTextJson", "--features", "attributes-only",
  "--keep-property-name", "--csharp-version", "8", "--namespace", "Ofac.Protocol",
  "--no-date-times", "--quiet",
  "-o", join(CS_OUT, "WireTypes.cs"),
]);
const banner =
  "// <auto-generated/>\n// Generated by protocol/tools/codegen.mjs — do not edit (regenerate: pnpm protocol:codegen).\n" +
  "#nullable enable annotations\n";
const csFile = join(CS_OUT, "WireTypes.cs");
writeFileSync(csFile, banner + (await BunFileText(csFile)));

async function BunFileText(p) {
  return await (await import("node:fs/promises")).readFile(p, "utf8");
}

// Mirror the normative schema files into the package (byte-identical copies).
rmSync(SCHEMA_OUT, { recursive: true, force: true });
mkdirSync(SCHEMA_OUT, { recursive: true });
for (const s of schemas) {
  writeFileSync(join(SCHEMA_OUT, basename(s)), readFileSync(s));
}
// Prettier pass so committed generated TS matches the repo's format gate.
const prettier = spawnSync("npx", ["--no-install", "prettier", "--write", join(TS_OUT, "*.ts")], {
  cwd: repo,
  stdio: "inherit",
});
if (prettier.status !== 0) process.exit(prettier.status ?? 1);

console.log(`codegen: ${schemas.length} schemas (${schemas.map((s) => basename(s)).length} files) rendered to ${TS_OUT} and ${CS_OUT}`);
