// The scripted AI worker (zero LLM): a real fleet child of the Gateway via
// @ofac/adapter, answering every work.assign deterministically —
//   execution 1 (no steers in inputs):  report artifact + structuredResult
//     { prRequest: {repo, head: ofac/<assignment slice>, base: main, …},
//       commentRequests: [{repo, issue, body: "On it …"}] }
//   execution 2+ (inputs.steers non-empty, the re-dispatch leg): folded
//     commentRequests ["steer incorporated: <directive>", …], no new PR.
// The @ofac/harness-deterministic completion law: upload report + manifest
// as artifacts, complete with resultManifestRef + resultDigest.
import { readFileSync } from "node:fs";
import { Buffer } from "node:buffer";
import {
  createAdapter,
  createArtifactClient,
  buildResultManifest,
  buildCompletedEvent,
  artifactUri,
} from "@ofac/adapter";
import { createConsoleLogger } from "@ofac/workspace-link";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const config = JSON.parse(readFileSync(flag("--config"), "utf8"));
const log = createConsoleLogger({ level: "info" });

const manifest = {
  apiVersion: "facilitator.framework/v1",
  kind: "CapabilityManifest",
  ownerTeam: "team-alpha",
  capabilities: [
    {
      id: "research.analyze",
      version: 1,
      execution: "asynchronous",
      acceptedContexts: ["uri-reference"],
      outputKinds: ["analysis.report"],
      outputMediaTypes: ["text/markdown"],
      supportsSteering: true,
      supportsCancellation: false,
      supportsNudge: false,
    },
  ],
};

async function onExecute(ctx) {
  const data = ctx.command.data;
  const workId = String(data.workId ?? ctx.executionId);
  const assignmentId = String(data.assignmentId ?? ctx.executionId);
  const inputs = data.inputs ?? {};
  const repo = String(inputs.repo ?? "octocat/Hello-World");
  const issue = String(inputs.issue ?? "7");
  const objective = String(inputs.objective ?? workId);
  const steers = Array.isArray(inputs.steers) ? inputs.steers : [];
  ctx.publishProgress(`accepted: scripted analysis for ${workId}`);

  const report = Buffer.from(
    `# Scripted report ${workId}\nobjective: ${objective}\nsteers: ${String(steers.length)}\n`,
    "utf8",
  );
  const client = createArtifactClient({
    baseUrl: config.kernelUrl,
    token: config.kernelToken ?? config.token,
  });
  const createdAt = new Date().toISOString();
  const reportArtifact = await client.upload(report, {
    mediaType: "text/markdown",
    workId,
    assignmentId,
    retentionPolicy: "30d",
  });
  const structuredResult =
    steers.length > 0
      ? {
          steeringDirectives: steers.length,
          commentRequests: steers.map((directive, i) => ({
            repo,
            issue,
            body: `steer incorporated: ${String(directive)} (#${String(i)})`,
          })),
        }
      : {
          steeringDirectives: 0,
          prRequest: {
            repo,
            head: `ofac/${assignmentId.replace(/-/g, "").slice(0, 8)}`,
            base: "main",
            title: objective.slice(0, 200),
            body: "Generated by the scripted worker.",
          },
          commentRequests: [{ repo, issue, body: "On it — work started." }],
        };
  const manifestDoc = buildResultManifest({
    manifestId: `man-${ctx.executionId}`,
    workId,
    assignmentId,
    capability: "research.analyze",
    summary: "scripted analysis complete",
    structuredResult,
    outputs: [
      {
        artifactId: reportArtifact.artifactId,
        mediaType: "text/markdown",
        size: report.length,
        digest: reportArtifact.digest,
        artifactUri: artifactUri(workId, assignmentId, reportArtifact.artifactId),
        createdBy: `workspace:${config.childWorkspaceId}`,
        createdAt,
        kind: "analysis.report",
        classification: "internal",
      },
    ],
    createdAt,
  });
  const stored = await client.upload(manifestDoc.document, {
    mediaType: "application/json",
    workId,
    assignmentId,
    retentionPolicy: "30d",
  });
  ctx.publishEvent(
    buildCompletedEvent(
      ctx,
      { manifestId: `man-${ctx.executionId}`, workId, assignmentId },
      {
        manifestRef: artifactUri(workId, assignmentId, stored.artifactId),
        digest: manifestDoc.digest,
      },
    ),
  );
  return { kind: "completed" };
}

const handle = await createAdapter({
  childWorkspaceId: config.childWorkspaceId,
  token: config.token,
  kernel: { baseUrl: config.kernelUrl, token: config.kernelToken ?? config.token },
  manifest,
  transport: { socketPath: config.socket },
  descriptor: {
    invocation: "sdk",
    supports: { steer: true, interrupt: false, resume: "restart-with-context" },
  },
  hooks: {
    onExecute,
    onSteer: (directive) => {
      log.info("scripted-steer", { directive: String(directive) });
    },
  },
  heartbeatSeconds: 2,
  restartBackoffMs: [],
  logger: log,
});
await handle.ready();
process.stdout.write(`worker ready childId=${config.childWorkspaceId}\n`);
process.on("SIGTERM", () => {
  process.exit(0);
});
